#!/usr/bin/env node
// The session handoff, written by a script instead of a model: one small file a new lead session reads first, so
// it can clear its context after every ship and still continue. ship.mjs writes it after each commit.
//   node <tools>/handoff.mjs          writes .agent-lead/handoff.md and prints one line
// It holds: the branch and last commit, the next plan item, the last status lines, the newest briefs and whether
// their reports exist, the workers and their state, and uncommitted files.
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { abs, git, run, toolsDir } from './lib.mjs'

const dir = abs('.agent-lead')
mkdirSync(dir, { recursive: true })
const tool = (name, ...a) => run('node', [path.join(toolsDir, `${name}.mjs`), ...a]).stdout.trim()
const head = git('log', '--oneline', '-3').stdout.trim()
const branch = git('branch', '--show-current').stdout.trim()
const dirty = git('status', '--porcelain').stdout.split('\n').filter((l) => l && !l.includes('.agent-lead/handoff.md'))
const statusFile = path.join(dir, 'status.md')
const status = existsSync(statusFile) ? readFileSync(statusFile, 'utf8').split('\n').filter((l) => l.startsWith('- ')).slice(-5) : []
const briefsDir = path.join(dir, 'briefs')
const briefs = existsSync(briefsDir)
  ? readdirSync(briefsDir).filter((f) => f.endsWith('.md') && !f.endsWith('.report.md')).map((f) => ({ f, t: statSync(path.join(briefsDir, f)).mtimeMs })).sort((a, b) => b.t - a.t).slice(0, 4)
      .map(({ f }) => `- \`${f}\`: ${existsSync(path.join(briefsDir, f.replace(/(-\d+)?\.md$/, '.report.md'))) ? 'report written' : 'no report yet'}`)
  : []
const next = tool('next').split('\n').filter(Boolean).slice(0, 3)
const workers = tool('worker', 'list').split('\n').filter((l) => l && !l.startsWith('no workers'))
const md = `# Handoff (${new Date().toISOString().slice(0, 16).replace('T', ' ')} UTC)

Generated by handoff.mjs after each ship. Read this first, then only the files it points to. LEAD.md has the
project's fixed facts (paths, commands, conventions).

## Where things stand
- Branch \`${branch}\`. Last commits:
${head.split('\n').map((l) => `  - ${l}`).join('\n')}
- Uncommitted in the lead checkout: ${dirty.length ? dirty.slice(0, 8).map((l) => '`' + l.trim() + '`').join(', ') : 'nothing'}.

## Next item
${next.length ? next.map((l) => `    ${l}`).join('\n') : '    (no plan found)'}

## Last status lines
${status.join('\n') || '- (none)'}

## Newest briefs
${briefs.join('\n') || '- (none)'}

## Workers
${workers.map((l) => `- ${l}`).join('\n') || '- one worker, as LEAD.md says (no parallel workers registered)'}
`
writeFileSync(path.join(dir, 'handoff.md'), md)
console.log(`.agent-lead/handoff.md written (about ${Math.round(md.length / 4)} tokens): start the next session from it`)
