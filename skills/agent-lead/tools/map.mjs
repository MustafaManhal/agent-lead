#!/usr/bin/env node
// Token saver: a small map of the repository (commands, layout, every source file with its size and what it
// exports), so the lead and the worker open the right file first instead of searching. Generated, never edited.
//   node <tools>/map.mjs [--out <file>] [--max <files>]     default out: "map" in the config, else .agent-lead/repo-map.md
// ship.mjs rebuilds it when the file already exists, so it stays current. Point briefs at it.
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { abs, config, options, root } from './lib.mjs'

const args = process.argv.slice(2)
const o = options(args)
const out = abs(o.opt('--out') ?? config.map ?? '.agent-lead/repo-map.md')
const MAX = Number(o.opt('--max', 300))
const SKIP = new Set(['node_modules', '.git', 'dist', 'build', '.next', 'coverage', 'vendor', 'target', '.turbo', '.cache', 'out', '.agent-lead'])
const GENERATED = ['dist', 'build', '.next', 'coverage', 'out', 'target'].filter((d) => existsSync(path.join(root, d)))
const files = []
const walk = (dir) => {
  for (const e of readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    if (SKIP.has(e.name) || e.name.startsWith('.')) continue
    const p = path.join(dir, e.name)
    if (e.isDirectory()) walk(p)
    else if (config.sourceExts.some((x) => e.name.endsWith(x)) && statSync(p).size < 1_000_000) files.push(p)
  }
}
const roots = config.sources.filter((d) => existsSync(abs(d)))
for (const d of roots.length ? roots : ['.']) walk(abs(d))
const NAMES = [
  /^export\s+(?:default\s+)?(?:async\s+)?(?:function\*?|const|let|class|interface|type|enum)\s+(\w+)/gm,
  /^(?:async\s+)?(?:def|class)\s+(\w+)/gm,
  /^func\s+(?:\([^)]*\)\s*)?([A-Z]\w*)/gm,
  /^pub\s+(?:async\s+)?(?:fn|struct|enum|trait)\s+(\w+)/gm,
]
const byDir = new Map()
for (const f of files.slice(0, MAX)) {
  const text = readFileSync(f, 'utf8')
  const names = [...new Set(NAMES.flatMap((r) => [...text.matchAll(r)].map((m) => m[1])))]
  const rel = path.relative(root, f)
  const dir = path.dirname(rel)
  if (!byDir.has(dir)) byDir.set(dir, [])
  byDir.get(dir).push(`- \`${path.basename(rel)}\` (${text.split('\n').length})${names.length ? ': ' + names.slice(0, 10).join(', ') + (names.length > 10 ? ', …' : '') : ''}`)
}
let pkg = null
try { pkg = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8')) } catch {}
const scripts = Object.entries(pkg?.scripts ?? {}).filter(([k]) => /^(dev|start|build|test|lint|typecheck|e2e)/.test(k)).map(([k, v]) => `- \`${k}\`: \`${String(v).slice(0, 90)}\``)
const top = readdirSync(root, { withFileTypes: true }).filter((e) => e.isDirectory() && !SKIP.has(e.name) && !e.name.startsWith('.')).map((e) => `\`${e.name}/\``)
const md = `# Repo map

Generated by agent-lead's map.mjs; do not edit. Open the file this map names, at the declaration you need
(\`outline.mjs\`, \`show.mjs\`), instead of searching the tree.

## Commands
${config.checks.map((c) => `- check \`${c.name}\`: \`${c.run}\``).join('\n') || '- (no checks detected)'}
${scripts.join('\n')}

## Layout
Top level: ${top.join(', ') || '(flat)'}. Plan: \`${config.plan ?? 'none'}\`.${pkg?.main ? ` Entry: \`${pkg.main}\`.` : ''}

## Do not edit
${[...GENERATED.map((d) => `\`${d}/\` (generated)`), 'lockfiles and dependency lists', '`.agent-lead/` and the plan (the lead owns them)', '`.env*`'].map((x) => `- ${x}`).join('\n')}

## Source files (lines): exports
${[...byDir.entries()].map(([d, rows]) => `### ${d}/\n${rows.join('\n')}`).join('\n\n')}
${files.length > MAX ? `\n… ${files.length - MAX} more files not listed (raise --max).\n` : ''}`
mkdirSync(path.dirname(out), { recursive: true })
writeFileSync(out, md)
console.log(`${path.relative(root, out)}: ${Math.min(files.length, MAX)} files in ${byDir.size} folders, about ${Math.round(md.length / 4)} tokens`)
